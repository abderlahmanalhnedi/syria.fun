import { localized, t } from './i18n.js';
import { url, element, icon } from './dom.js';
export function createCard(item, media) {
  const card = element('article', 'card');
  card.dataset.id = item.id;
  card.dataset.category = item.category;
  card.dataset.kind = item.kind;
  const imageBox = element('div', 'card-image');
  const img = element('img');
  const asset = media[item.photo || item.id];
  img.src = url(asset?.file || `assets/images/${item.id}.svg`);
  img.width = 640;
  img.height = 440;
  img.loading = 'lazy';
  img.alt = localized(item.name);
  imageBox.append(img);
  const save = element('button', 'favorite-button');
  save.type = 'button';
  save.dataset.favorite = item.id;
  save.append(icon('heart'));
  imageBox.append(save);
  card.append(imageBox);
  const content = element('div', 'card-content');
  content.append(element('p', 'eyebrow', t(item.category)));
  const heading = element('h2', 'card-title');
  const link = element('a', '', localized(item.name));
  link.href = url(item.href);
  heading.append(link);
  content.append(heading, element('p', 'card-description', localized(item.description)));
  const actions = element('div', 'card-actions');
  const read = element('a', 'text-link', t('read'));
  read.href = url(item.href);
  read.append(icon('arrow'));
  const quick = element('button', 'quick-button', t('quickView'));
  quick.type = 'button';
  quick.dataset.preview = item.id;
  actions.append(read, quick);
  content.append(actions);
  card.append(content);
  return card;
}
